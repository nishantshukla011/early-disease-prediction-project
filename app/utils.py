from fpdf import FPDF
import datetime
import io


def _latin1(text):
    return str(text).encode("latin-1", errors="replace").decode("latin-1")


def generate_pdf(xray_path, gradcam_path, diagnosis):
    pdf = FPDF()
    pdf.set_auto_page_break(auto=True, margin=15)
    pdf.add_page()

    # Header
    pdf.set_font("Arial", 'B', 16)
    pdf.cell(200, 10, "Chest X-Ray Analysis Report (Educational Demo)", ln=True, align='C')
    pdf.ln(5)

    # Date
    pdf.set_font("Arial", size=12)
    pdf.cell(200, 10, f"Date: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}", ln=True)
    pdf.ln(5)

    # X-ray Image
    pdf.set_font("Arial", 'B', 12)
    pdf.cell(200, 10, "Uploaded X-Ray:", ln=True)
    pdf.image(xray_path, x=30, w=150)
    pdf.ln(10)

    # Model output
    pdf.set_font("Arial", 'B', 12)
    pdf.cell(200, 10, "Automated Model Output:", ln=True)
    pdf.set_font("Arial", size=10)
    pdf.multi_cell(0, 6, _latin1(diagnosis))
    pdf.ln(10)

    # Grad-CAM Image
    pdf.set_font("Arial", 'B', 12)
    pdf.cell(200, 10, "Grad-CAM Heatmap:", ln=True)
    pdf.image(gradcam_path, x=30, w=150)
    pdf.ln(10)

    # Heatmap Explanation
    pdf.set_font("Arial", 'B', 12)
    pdf.cell(200, 10, "Heatmap Interpretation:", ln=True)
    pdf.set_font("Arial", size=10)
    pdf.multi_cell(
        0, 6,
        "The Grad-CAM heatmap shows the image regions that most influenced the "
        "model's highest-scoring output. It is a visual aid for understanding "
        "the model; it does not mark or confirm a lesion."
    )
    pdf.ln(10)

    # Footer
    pdf.set_font("Arial", 'I', 10)
    pdf.cell(200, 10, "Generated by the AI-Powered Early Disease Prediction System (educational demo).", ln=True)

    # Convert PDF to bytes
    pdf_output = io.BytesIO()
    pdf_output.write(pdf.output(dest='S').encode('latin1'))
    pdf_output.seek(0)

    return pdf_output.getvalue()
